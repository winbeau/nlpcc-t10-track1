"""Score Track 1 dev predictions via the official offline evaluator.

Never re-implement the metric — always shell out to the OFFICIAL scorer:
  $DATA_ROOT/offline_eval/evaluate.py --track 1 --match id

Design contract:
  - --gold  defaults to data/dev_gold.jsonl (generated by build_dataset.py;
            contains record-level {id, sentence_label} with gold types).
  - --pred  is the aggregate.py output: {id, labels} per record.
  - Subprocess call to the official evaluate.py; parses the resulting
    <pred_stem>_eval_result.json for structured metrics.
  - Prints: score / macro_f1 / pem / sentence_accuracy + per-label F1 table
    (sorted by F1 ascending so the bottleneck label shows first).
  - Optional --log <csv>: appends one row (timestamp, tag, score, macro_f1, pem,
    plus per-label F1s) to a CSV experiment ledger for cross-run comparison.
    The ledger is created with a header row if it does not yet exist.

CLI:
  python -m nlpcc_t10.eval_local \\
      --pred outputs/dev_submission.jsonl \\
      --gold data/dev_gold.jsonl \\
      --data-root ../NLPCC-2026-Task10-Science \\
      [--tag oversample3x_thr0.6] \\
      [--log notes/experiments.csv]
"""

from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path


TRACK1_LABELS = [
    "Supported",
    "Unsupported Causal Mechanistic",
    "Unsupported Entity",
    "Scope Overgeneralization",
    "Contradiction",
]


# ──────────────────────────────────────────────────────────────────────────────
# Subprocess scorer
# ──────────────────────────────────────────────────────────────────────────────

def run_official_evaluator(
    data_root: Path,
    gold_path: Path,
    pred_path: Path,
    output_path: Path,
    match: str = "id",
) -> dict:
    """Call the official evaluate.py subprocess and return the parsed JSON report.

    The evaluator writes a JSON result file; we read and return it.
    """
    evaluator = data_root / "offline_eval" / "evaluate.py"
    if not evaluator.exists():
        raise FileNotFoundError(
            f"Official evaluator not found: {evaluator}\n"
            f"Check --data-root (currently {data_root})."
        )

    cmd = [
        sys.executable,
        str(evaluator),
        "--track", "1",
        "--gold", str(gold_path),
        "--pred", str(pred_path),
        "--output", str(output_path),
        "--match", match,
    ]

    result = subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )

    if result.returncode != 0:
        raise RuntimeError(
            f"Official evaluator exited with code {result.returncode}.\n"
            f"stdout: {result.stdout}\n"
            f"stderr: {result.stderr}"
        )

    # The evaluator prints a concise summary to stdout; forward it.
    if result.stdout.strip():
        print(result.stdout, end="" if result.stdout.endswith("\n") else "\n")

    if not output_path.exists():
        raise FileNotFoundError(
            f"Evaluator did not produce result file: {output_path}\n"
            f"evaluator stdout: {result.stdout}\n"
            f"evaluator stderr: {result.stderr}"
        )

    with output_path.open("r", encoding="utf-8") as f:
        return json.load(f)


# ──────────────────────────────────────────────────────────────────────────────
# Report rendering
# ──────────────────────────────────────────────────────────────────────────────

def _fmt(v: float, pct: bool = True) -> str:
    return f"{v * 100:.2f}%" if pct else f"{v:.6f}"


def print_report(report: dict) -> None:
    """Print a concise, human-readable metric summary."""
    print()
    print("=" * 62)
    print("  TRACK 1 — OFFICIAL SCORE REPORT")
    print("=" * 62)
    print(f"  score        : {_fmt(report['score'])}   (Macro-F1 + PEM) / 2")
    print(f"  macro_f1     : {_fmt(report['macro_f1'])}")
    print(f"  pem          : {_fmt(report['pem'])}   paragraph exact match")
    print(f"  sent_accuracy: {_fmt(report['sentence_accuracy'])}")
    print(f"  num_samples  : {report['num_samples']} records")
    print(f"  num_sentences: {report['num_sentences']}")
    print()

    per_label = report.get("per_label", {})
    if per_label:
        print("  Per-label F1 (ascending — bottleneck first):")
        print(f"  {'Label':<35} {'F1':>7}  {'P':>7}  {'R':>7}  {'Support':>8}  {'Pred':>7}")
        print("  " + "-" * 60)
        # Sort ascending by F1 so the weakest label is first
        sorted_labels = sorted(
            TRACK1_LABELS, key=lambda lbl: per_label.get(lbl, {}).get("f1", 0.0)
        )
        for lbl in sorted_labels:
            m = per_label.get(lbl, {})
            f1 = m.get("f1", 0.0)
            p = m.get("precision", 0.0)
            r = m.get("recall", 0.0)
            sup = m.get("support", 0)
            pred = m.get("predicted", 0)
            print(
                f"  {lbl:<35} {_fmt(f1):>7}  {_fmt(p):>7}  {_fmt(r):>7}  {sup:>8}  {pred:>7}"
            )
    print("=" * 62)
    print()


# ──────────────────────────────────────────────────────────────────────────────
# CSV ledger
# ──────────────────────────────────────────────────────────────────────────────

def _label_csv_key(label: str) -> str:
    """Shorten label names for CSV columns."""
    return label.replace(" ", "_").lower()


def append_to_ledger(
    ledger_path: Path,
    tag: str,
    pred_path: str,
    report: dict,
) -> None:
    """Append one row to the experiment CSV ledger (create with header if new)."""
    ledger_path.parent.mkdir(parents=True, exist_ok=True)
    per_label = report.get("per_label", {})

    header = [
        "timestamp", "tag", "pred",
        "score", "macro_f1", "pem", "sentence_accuracy",
        "num_samples", "num_sentences",
    ] + [f"f1_{_label_csv_key(lbl)}" for lbl in TRACK1_LABELS]

    row = {
        "timestamp": datetime.now(tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "tag": tag,
        "pred": pred_path,
        "score": f"{report['score']:.6f}",
        "macro_f1": f"{report['macro_f1']:.6f}",
        "pem": f"{report['pem']:.6f}",
        "sentence_accuracy": f"{report['sentence_accuracy']:.6f}",
        "num_samples": str(report["num_samples"]),
        "num_sentences": str(report["num_sentences"]),
    }
    for lbl in TRACK1_LABELS:
        row[f"f1_{_label_csv_key(lbl)}"] = f"{per_label.get(lbl, {}).get('f1', 0.0):.6f}"

    write_header = not ledger_path.exists() or ledger_path.stat().st_size == 0
    with ledger_path.open("a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=header)
        if write_header:
            writer.writeheader()
        writer.writerow(row)

    print(f"[eval_local] Appended to ledger: {ledger_path}", file=sys.stderr)


# ──────────────────────────────────────────────────────────────────────────────
# CLI
# ──────────────────────────────────────────────────────────────────────────────

def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Score Track 1 dev predictions via the official evaluator."
    )
    p.add_argument(
        "--pred", required=True,
        help="aggregate.py output JSONL: {id, labels} per record."
    )
    p.add_argument(
        "--gold", default="data/dev_gold.jsonl",
        help="Gold JSONL (build_dataset.py dev_gold.jsonl). Default: data/dev_gold.jsonl"
    )
    p.add_argument(
        "--data-root", default="../NLPCC-2026-Task10-Science",
        help="Path to official task repo containing offline_eval/evaluate.py."
    )
    p.add_argument(
        "--match", choices=("auto", "id", "line"), default="id",
        help="Record-matching mode for the official evaluator (default: id)."
    )
    p.add_argument(
        "--tag", default="",
        help="Experiment tag appended to the CSV ledger row."
    )
    p.add_argument(
        "--log", default="",
        help="CSV ledger path; row is appended on each run. Created if absent."
    )
    p.add_argument(
        "--keep-result", action="store_true",
        help="Keep the evaluator's result JSON file (default: delete after reading)."
    )
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)

    pred_path = Path(args.pred)
    gold_path = Path(args.gold)
    data_root = Path(args.data_root)

    for p, name in [(pred_path, "--pred"), (gold_path, "--gold")]:
        if not p.exists():
            print(f"error: {name} file not found: {p}", file=sys.stderr)
            return 2

    # Determine result JSON output path: next to pred, auto-named by evaluate.py convention
    result_path = pred_path.with_name(f"{pred_path.stem}_eval_result.json")

    print(
        f"[eval_local] Scoring {pred_path.name} against {gold_path.name} ...",
        file=sys.stderr,
    )

    try:
        report = run_official_evaluator(
            data_root=data_root,
            gold_path=gold_path,
            pred_path=pred_path,
            output_path=result_path,
            match=args.match,
        )
    except (FileNotFoundError, RuntimeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print_report(report)

    if not args.keep_result and result_path.exists():
        result_path.unlink()

    if args.log:
        append_to_ledger(
            ledger_path=Path(args.log),
            tag=args.tag,
            pred_path=str(pred_path),
            report=report,
        )

    # Print final score for easy shell capture
    print(f"SCORE={report['score']:.6f}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
